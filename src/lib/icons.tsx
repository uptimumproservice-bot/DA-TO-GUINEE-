import React, { forwardRef } from 'react';

export type IconNode = Array<[tag: string, attrs: Record<string, string | number>]>;

export interface LucideProps extends React.SVGProps<SVGSVGElement> {
  size?: string | number;
  absoluteStrokeWidth?: boolean;
  color?: string;
  strokeWidth?: string | number;
}

export type LucideIcon = React.ForwardRefExoticComponent<
  Omit<LucideProps, 'ref'> & React.RefAttributes<SVGSVGElement>
>;

function mergeClasses(...classes: Array<string | undefined | false>): string {
  return classes
    .filter((c): c is string => Boolean(c))
    .join(' ')
    .trim();
}

function createLucideIcon(iconName: string, iconNode: IconNode): LucideIcon {
  const Component = forwardRef<SVGSVGElement, LucideProps>(
    (
      { color = 'currentColor', size = 24, strokeWidth = 2, absoluteStrokeWidth, className = '', children, ...rest },
      ref
    ) => {
      const computedStroke = absoluteStrokeWidth ? (Number(strokeWidth) * 24) / Number(size) : strokeWidth;
      const hasA11y = Boolean(rest['aria-label'] || rest['aria-labelledby'] || rest.role === 'img');
      return (
        <svg
          ref={ref}
          xmlns="http://www.w3.org/2000/svg"
          width={size}
          height={size}
          viewBox="0 0 24 24"
          fill="none"
          stroke={color}
          strokeWidth={computedStroke}
          strokeLinecap="round"
          strokeLinejoin="round"
          className={mergeClasses('lucide', `lucide-${iconName}`, className)}
          {...(!children && !hasA11y ? { 'aria-hidden': 'true' } : {})}
          {...rest}
        >
          {iconNode.map(([tag, attrs]) => React.createElement(tag, attrs))}
          {children}
        </svg>
      );
    }
  );
  Component.displayName = iconName;
  return Component;
}

